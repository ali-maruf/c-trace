// Generate TypeScript types for the C-Trace API from its OpenAPI schema (FastAPI).
//   npm run gen:api       (needs the Python workspace: `make setup` at the repo root)
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const root = path.resolve(import.meta.dirname, "../../..");
const json = execFileSync("uv", ["run", "--quiet", "python", "-c",
  "import json; from ctrace_api.main import app; print(json.dumps(app.openapi()))"], { cwd: root, encoding: "utf8", maxBuffer: 32 * 1024 * 1024 });
const spec = JSON.parse(json);
mkdirSync(path.join(import.meta.dirname, "../lib"), { recursive: true });
writeFileSync(path.join(import.meta.dirname, "../lib/openapi.json"), JSON.stringify(spec, null, 1));
const ast = await openapiTS(spec);
writeFileSync(path.join(import.meta.dirname, "../lib/api-schema.d.ts"), `/* Generated by scripts/gen-api.mjs from the C-Trace API OpenAPI schema. Do not edit. */\n${astToString(ast)}`);
console.log(`[C-Trace] ${Object.keys(spec.paths).length} API paths → lib/api-schema.d.ts`);
