"use client";

import { useQuery } from "@tanstack/react-query";
import Image from "next/image";
import Link from "next/link";
import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";
import { ErrorState, Loading } from "@/components/ui";
import { api } from "@/lib/api";

export default function ModelCardPage() {
  const q = useQuery({ queryKey: ["model-card"], queryFn: () => api<{ markdown: string }>("/v1/model-card") });
  return (
    <div className="mx-auto max-w-4xl px-4 py-8 sm:px-6">
      <Link href="/"><Image src="/brand/c-trace-logo.svg" alt="C-Trace" width={140} height={30} /></Link>
      <p className="mt-6 text-sm text-slate">Generated by code from the training and evaluation runs; nothing here is typed in by hand.</p>
      {q.isLoading && <Loading />}
      {q.error && <ErrorState error={q.error} />}
      {q.data && (
        <article className="prose-ctrace mt-4">
          <ReactMarkdown remarkPlugins={[remarkGfm]}>{q.data.markdown}</ReactMarkdown>
        </article>
      )}
    </div>
  );
}
